const dict = { en, zh }

export type DictKey = keyof typeof en

export const DAY_KEYS: DictKey[] = ['day.mon', 'day.tue', 'day.wed', 'day.thu', 'day.fri', 'day.sat', 'day.sun']
export const SHIFT_KEYS: DictKey[] = ['shift.morning', 'shift.noon', 'shift.evening']

interface LangCtx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: DictKey, vars?: Record<string, string | number>) => string
}

const Ctx = createContext<LangCtx>(null as unknown as LangCtx)

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem('meiti2:lang')
    return saved === 'zh' || saved === 'en' ? saved : 'en'
  })
  const setLang = (l: Lang) => {
    setLangState(l)
    localStorage.setItem('meiti2:lang', l)
  }
  const t = (key: DictKey, vars?: Record<string, string | number>) => {
    let s: string = dict[lang][key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
    return s
  }
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
}

export function useT() {
  return useContext(Ctx)
}
